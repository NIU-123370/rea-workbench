// The id shape, on its own (DESIGN §4).
//
// This file has no dependency that a browser cannot run: `identity.ts` next door owns
// `newId()`, which needs `node:crypto`. A screen that only has to *recognise* an
// identifier - the client bundle, for instance - imports the shape from here rather than
// dragging a Node builtin into the browser.

export type Id = string & { readonly idBrand: unique symbol };

export const ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function isId(value: unknown): value is Id {
  return typeof value === "string" && ID_PATTERN.test(value);
}

export function asId(value: string): Id {
  if (!isId(value)) {
    throw new TypeError("id must be an opaque UUID generated by the workbench");
  }
  return value;
}
