// The Builder generation seam (DESIGN §7.3, §10 / PRD F08 A07, issue #19).
//
// Two things make this a boundary rather than a code generator with a permission
// check bolted on:
//
//   1. The only input is a frozen blueprint handoff. There is no target id, no
//      vector id and no artifact key in the request, so a holdout sample cannot be
//      named from here even by a caller that knew its id (§7.1: holdout stays with
//      the evaluator; §7.3: the Builder reads the blueprint, nothing else).
//   2. A candidate is a *claim about generated bytes*, never a verdict. This module
//      cannot write a verification row and does not import the service that does;
//      the most it can say is "these files, this digest".

// `gateFail` already returns the failure shape; this helper exists for the sites
// that hold a bare GateFailure. Accepting both keeps a call site from silently
// double-wrapping, which is how a refusal turns into an unparseable error object.
function err(failure: GateFailure | Err<GateFailure>): Err<GateFailure> {
  return "ok" in failure ? failure : { ok: false, error: failure };
}

// A producer that refuses says so with a name. The service maps it onto a §8 code and
// journals it; an unlabelled exception would arrive as a generic failure and hide which
// boundary the role hit.
export class BuilderRoleFailure extends Error {
  public override readonly name: string = "BuilderRoleFailure";
  readonly reason: string;
  readonly details: string[];

  constructor(reason: string, details: string[] = []) {
    super(reason);
    this.reason = reason;
    this.details = details;
  }
}

export type GenerationBudget = {
  maxAttemptsPerBlueprint: number;
  // Wall-clock bound supplied by the caller and checked against the worker's clock,
  // so a queued generation cannot outlive the reason it was asked for.
  deadlineAt: Instant | null;
};

export type CandidateCommit = {
  candidateId: Id;
  digest: Digest;
  blueprintDigest: Digest;
  attempt: number;
  files: { path: string; sha256: Digest; byteLength: number }[];
  openApiVersion: string;
};

// The handoff shape, named from the one function that consumes it rather than
// re-declared here: a second spelling is a second thing that can drift.
export type BuilderHandoff = Parameters<typeof buildTargetOpenApi>[0];

// The generation itself: a pure function of the handoff. The Builder role's own program
// (`apps/worker/builder-child.ts`) calls exactly this, so the isolated process and the
// in-process path cannot grow into two different generators. Everything the candidate is
// made of - the adapter source, the OpenAPI document and its digest, the entry manifest -
// derives from the frozen blueprint and nothing else.
export function produceCandidateFiles(handoff: BuilderHandoff, limits: CanonicalLimits): CandidateFile[] {
  const openApi = buildTargetOpenApi(handoff);
  const digest = openApiDigest(openApi.document, limits);
  const operations: ReviewedOperation[] = handoff.contractRevisions.flatMap((entry) =>
    entry.httpOperations.map((operation) => ({
      operationId: operation.operationId,
      method: operation.method,
      path: operation.path,
    })),
  );
  const manifest = candidateManifest({
    schemaVersion: 1,
    entry: "adapter.ts",
    operationIds: operations.map((operation) => operation.operationId),
    openApiDigest: digest,
  });
  return [
    { path: "adapter.ts", body: adapterSource(operations), mediaType: "text/typescript" },
    { path: "openapi.json", body: JSON.stringify(openApi.document), mediaType: "application/json" },
    { path: "candidate-manifest.json", body: JSON.stringify(manifest), mediaType: "application/json" },
  ];
}

export class BuilderService {
  readonly storage: StorageWriterPort;
  readonly artifacts: ArtifactPort;
  readonly limits: CanonicalLimits;
  // The worker injects the process-backed producer, so the bytes of a candidate are made
  // outside this process and this service only ever publishes and commits what arrives.
  // Async because the production producer spawns a child; the default is the pure function.
  readonly produce: (handoff: BuilderHandoff, limits: CanonicalLimits) => Promise<CandidateFile[]>;

  constructor(deps: {
    storage: StorageWriterPort;
    artifacts: ArtifactPort;
    limits: CanonicalLimits;
    produce?: (handoff: BuilderHandoff, limits: CanonicalLimits) => Promise<CandidateFile[]>;
  }) {
    this.storage = deps.storage;
    this.artifacts = deps.artifacts;
    this.limits = deps.limits;
    this.produce = deps.produce ?? (async (handoff, limits) => produceCandidateFiles(handoff, limits));
  }

  async generate(
    projectId: Id,
    actor: Actor,
    blueprintId: Id,
    input: { budget: GenerationBudget; generator: JsonObject; jobId: Id },
  ): Promise<Result<CandidateCommit, GateFailure>> {
    // Only the Builder role generates. An inspector or reviewer asking for a
    // candidate would be the control plane writing code it then reviews.
    if (!isBuilder(actor)) {
      recordDeny(this.storage, {
        projectId,
        actor,
        resourceType: "candidate",
        action: "builder.generate",
        resourceId: null,
        decision: "deny",
        reasonCode: "only-the-builder-generates",
        metadata: {},
      });
      return err(
        gateFail(
          "ACCESS_DENIED",
          "only-the-builder-generates",
          "generation is the Builder's operation, not a control-plane one",
          { actorKind: actor.actorKind },
        ),
      );
    }

    const loaded = this.storage.transact((tx) => {
      const blueprint = tx.getBlueprint(projectId, blueprintId);
      if (blueprint === null) return null;
      const artifact = tx.getArtifact(projectId, blueprint.artifactId);
      if (artifact === null) return null;
      return { blueprint, artifact };
    });
    if (!loaded.ok) return gateFail("INVALID_INPUT", loaded.error.code, loaded.error.message);
    const found = loaded.value;
    if (found === null) {
      recordDeny(this.storage, {
        projectId,
        actor,
        resourceType: "candidate",
        action: "builder.generate",
        resourceId: blueprintId,
        decision: "deny",
        reasonCode: "blueprint-unreadable",
        metadata: {},
      });
      return gateFail("NOT_FOUND", "blueprint-unreadable", "no such blueprint or its payload is gone");
    }
    const { blueprint, artifact } = found;
    if (artifact.sha256 === null) {
      return err(
        gateFail("REA_CONTRACT_MISMATCH", "blueprint-digest-withheld", "the blueprint payload carries no digest", {
          artifactId: artifact.id,
        }),
      );
    }
    const bytes = await this.artifacts.read(projectId, artifact.storageKey);
    if (!bytes.ok) return gateFail("REA_CONTRACT_MISMATCH", "blueprint-unreadable", bytes.error.code);
    if (digestBytes(bytes.value) !== artifact.sha256) {
      return err(
        gateFail("REA_CONTRACT_MISMATCH", "blueprint-digest-mismatch", "the stored blueprint bytes changed", {
          artifactId: artifact.id,
        }),
      );
    }
    const parsedWire = builderBlueprintSchema.safeParse(parseJson(bytes.value));
    if (!parsedWire.success) {
      return err(
        gateFail(
          "REA_CONTRACT_MISMATCH",
          "blueprint-shape",
          `stored blueprint violates the Builder handoff at ${issueNames(parsedWire.error.issues).join(",")}`,
        ),
      );
    }
    // The stored payload must be the one the row's digest was computed over: a
    // rewritable blueprint would let a candidate be generated from content no one
    // approved while keeping the approved identity.
    if (parsedWire.data.blueprintDigest !== blueprint.digest || parsedWire.data.blueprintId !== blueprint.id) {
      return err(
        gateFail(
          "REA_CONTRACT_MISMATCH",
          "blueprint-row-disagreement",
          "the stored blueprint does not agree with its index row",
          { blueprintId },
        ),
      );
    }
    const payload = parsedWire.data as unknown as BlueprintPayload;

    const defects = generationDefects(payload);
    if (defects.length > 0) return blockedByReasons(defects, "BLUEPRINT_BLOCKED", "generation");

    const nowMs = Date.now();
    if (input.budget.deadlineAt !== null && instantToMs(input.budget.deadlineAt) < nowMs) {
      recordDeny(this.storage, {
        projectId,
        actor,
        resourceType: "candidate",
        action: "builder.generate",
        resourceId: blueprintId,
        decision: "deny",
        reasonCode: "generation-deadline-passed",
        metadata: { blueprintId },
      });
      return err(
        gateFail(
          "RESOURCE_LIMIT",
          "generation-deadline-passed",
          "the generation deadline passed before the builder ran",
          { deadlineAt: input.budget.deadlineAt },
        ),
      );
    }

    const prior = this.storage.transact((tx) => tx.listCandidatesForBlueprint(projectId, blueprintId));
    if (!prior.ok) return gateFail("INVALID_INPUT", prior.error.code, prior.error.message);
    const attempt = prior.value.length + 1;
    // §10: a fix loop has an explicit budget and stops when it is spent. It is not
    // "keep repairing until green", and the refusal says so instead of quietly
    // producing attempt N+1.
    if (attempt > input.budget.maxAttemptsPerBlueprint) {
      recordDeny(this.storage, {
        projectId,
        actor,
        resourceType: "candidate",
        action: "builder.generate",
        resourceId: blueprintId,
        decision: "deny",
        reasonCode: "generation-budget-exhausted",
        metadata: { blueprintId, attempt },
      });
      return err(
        gateFail(
          "RESOURCE_LIMIT",
          "generation-budget-exhausted",
          "the builder's attempt budget for this blueprint is spent",
          { attempt, maxAttempts: input.budget.maxAttemptsPerBlueprint },
        ),
      );
    }

    let files: CandidateFile[];
    try {
      files = await this.produce(payload, this.limits);
    } catch (failure) {
      const named = failure instanceof BuilderRoleFailure ? failure : null;
      const reason = named?.reason ?? "builder-producer-failed";
      recordDeny(this.storage, {
        projectId,
        actor,
        resourceType: "candidate",
        action: "builder.generate",
        resourceId: blueprintId,
        decision: "deny",
        reasonCode: reason,
        metadata: { blueprintId },
      });
      return err(
        gateFail(
          "CAPABILITY_UNAVAILABLE",
          reason,
          "the builder role did not produce a candidate",
          named === null ? {} : { details: named.details as unknown as JsonValue },
        ),
      );
    }

    const published: { file: CandidateFile; sha256: Digest; byteLength: number; storageKey: string }[] = [];
    for (const file of files) {
      const bytes = new TextEncoder().encode(file.body);
      const outcome = await this.artifacts.publish(projectId, "candidate", bytes, asDigest(digestBytes(bytes)));
      if (!outcome.ok) {
        return err(
          gateFail("CAPABILITY_UNAVAILABLE", outcome.error.code, `the candidate file ${file.path} could not be published`),
        );
      }
      published.push({
        file,
        sha256: outcome.value.sha256,
        byteLength: outcome.value.byteLength,
        storageKey: outcome.value.storageKey,
      });
    }
    const candidateDigest = asDigest(
      digestConcat(published.map((entry) => `${entry.file.path}:${entry.sha256}`).join("\n")),
    );

    const candidateId = newId();
    const artifactIds = published.map(() => newId());
    const createdAt = nowInstant();

    const committed = commitDecision<CandidateCommit>(this.storage, {
      projectId,
      actor,
      resourceType: "candidate",
      action: "builder.generate",
      resourceId: candidateId,
      allowReason: "candidate-generated",
      metadata: { blueprintId, attempt, candidateDigest },
      work: (tx): Step<CandidateCommit> => {
        // The blueprint must still be the one that was read, and the attempt count
        // must still be inside the budget: a fix loop that raced another generation
        // gets refused rather than double-counted.
        const stillThere = tx.getBlueprint(projectId, blueprintId);
        if (stillThere === null || stillThere.digest !== blueprint.digest) {
          return {
            kind: "failure",
            failure: gateFail("REVISION_CONFLICT", "blueprint-changed-under-generation", "the blueprint moved while the candidate was being generated"),
          };
        }
        const attempts = tx.listCandidatesForBlueprint(projectId, blueprintId).length;
        const job = tx.getJob(projectId, input.jobId);
        if (job === null || job.projectId !== projectId) {
          return {
            kind: "failure",
            failure: gateFail("NOT_FOUND", "generation-job-unknown", "the generation job is not this project's job"),
          };
        }
        if (attempts + 1 > input.budget.maxAttemptsPerBlueprint) {
          return {
            kind: "failure",
            failure: gateFail(
              "RESOURCE_LIMIT",
              "generation-budget-exhausted",
              "another generation spent the budget before this one committed",
              { attempts, maxAttempts: input.budget.maxAttemptsPerBlueprint },
            ),
          };
        }
        // §11 decides who may hold a result: a queued job passes through running first, and
        // a failed, cancelled or interrupted job never takes one. A repair attempt on a job
        // that already succeeded keeps it succeeded and re-points its result at the newest
        // candidate, which is what §5 means by 每次修复生成新 candidate.
        let finishedJob: JobRow;
        if (job.state === "succeeded") {
          finishedJob = { ...job, updatedAt: createdAt };
        } else {
          const started = job.state === "queued" ? transition(job, "running", createdAt) : job;
          const moved = started === null ? null : transition(started, "succeeded", createdAt);
          if (moved === null) {
            return {
              kind: "failure",
              failure: gateFail(
                "REVISION_CONFLICT",
                "generation-job-terminal",
                `a job in state ${job.state} does not take a result`,
                { jobState: job.state },
              ),
            };
          }
          finishedJob = moved;
        }
        let primaryArtifactId: Id = artifactIds[0] as Id;
        const artifactRefs: Id[] = [];
        published.forEach((entry, index) => {
          // Same bytes, same project, same class: one artifact row. A candidate that
          // reused an earlier candidate's file points at the row that already exists
          // instead of failing on the store's dedupe key (§5).
          const existing = tx.findArtifactByDigest(projectId, "candidate", entry.sha256);
          const artifactId = existing === null ? (artifactIds[index] as Id) : existing.id;
          if (existing === null) {
            tx.insertArtifact({
              id: artifactId,
              projectId,
              jobId: null,
              class: "candidate",
              sha256: entry.sha256,
              digestReason: null,
              byteLength: entry.byteLength,
              storageKey: entry.storageKey,
              mediaType: entry.file.mediaType,
              createdAt,
            });
          }
          if (index === 0) primaryArtifactId = artifactId;
          artifactRefs.push(artifactId);
        });
        const row: CandidateRow = {
          id: candidateId,
          projectId,
          blueprintId,
          jobId: input.jobId,
          artifactId: primaryArtifactId,
          digest: candidateDigest,
          generatorJson: { ...input.generator, attempt, openApiVersion: OPENAPI_VERSION },
          dependencyManifestJson: {
            files: published.map((entry, index) => ({
              path: entry.file.path,
              sha256: entry.sha256,
              artifactId: artifactRefs[index] as Id,
            })),
          },
        };
        tx.insertCandidate(row);
        // §8 line 294: a successful generation's job carries the candidate id as its
        // resultRef, and line 277's job page is the only documented way a client recovers
        // that id. Without this write the candidate exists, is addressable in the store, and
        // cannot be named by anything the UI is allowed to call.
        tx.updateJob({ ...finishedJob, resultRef: candidateId, updatedAt: createdAt });
        tx.appendEvent({
          projectId,
          type: "job.updated",
          aggregateId: job.id,
          payloadJson: { resourceIds: [job.id, candidateId], state: finishedJob.state },
          createdAt,
        });
        return {
          kind: "committed",
          value: {
            candidateId,
            digest: candidateDigest,
            blueprintDigest: blueprint.digest,
            attempt,
            files: published.map((entry) => ({
              path: entry.file.path,
              sha256: entry.sha256,
              byteLength: entry.byteLength,
            })),
            openApiVersion: OPENAPI_VERSION,
          },
        };
      },
    });
    if (!committed.ok) return err(committed.error);
    return { ok: true, value: committed.value.value };
  }
}

function instantToMs(value: Instant): number {
  const ms = Date.parse(value);
  return Number.isNaN(ms) ? 0 : ms;
}

function parseJson(bytes: Uint8Array): JsonValue {
  return JSON.parse(new TextDecoder("utf8", { fatal: true }).decode(bytes)) as JsonValue;
}

function digestConcat(text: string): Digest {
  // A sha256 over the ordered `path:digest` list, so renaming a file or swapping two
  // bodies is a different candidate digest.
  return asDigest(createHash("sha256").update(text, "utf8").digest("hex"));
}
